"""Streamlit user interface for the LearnSphere FAQ chatbot.

Run with:  streamlit run app.py
"""

import streamlit as st

from faq_chatbot.chatbot import build_chatbot
from faq_chatbot.config import ConfigError, Settings

SAMPLE_QUESTIONS = [
    "How do I reset my password?",
    "What is your refund policy?",
    "Do you offer student discounts?",
    "Can I download lessons to watch offline?",
]

st.set_page_config(page_title="LearnSphere FAQ Assistant", page_icon="💬")
st.title("💬 LearnSphere FAQ Assistant")
st.caption("Ask me anything about accounts, billing, courses or technical issues.")


# ---- configuration (fail early with a helpful message) ---------------------
try:
    settings = Settings.from_env()
except ConfigError as exc:
    st.error(f"Configuration error: {exc}")
    st.stop()

problems = settings.validate()
if problems:
    st.error("The app is not configured correctly yet:\n\n" + "\n".join(f"- {p}" for p in problems))
    st.info("Copy `.env.example` to `.env`, add your API key, and restart the app.")
    st.stop()

# ---- per-session state -----------------------------------------------------
if "chatbot" not in st.session_state:
    st.session_state.chatbot = build_chatbot(settings)
    st.session_state.messages = []  # what we render: dicts with role, content, sources


def clear_chat() -> None:
    st.session_state.chatbot.reset()
    st.session_state.messages = []


# ---- sidebar ---------------------------------------------------------------
with st.sidebar:
    st.header("About")
    mode = "retrieval only (no LLM)" if settings.provider == "none" else f"{settings.provider} / {settings.resolved_model}"
    st.write(f"**Mode:** {mode}")
    st.write(f"**FAQs loaded:** {len(st.session_state.chatbot.retriever.faqs)}")
    st.button("🗑️ Clear conversation", on_click=clear_chat, use_container_width=True)

    st.header("Try asking")
    for sample in SAMPLE_QUESTIONS:
        if st.button(sample, use_container_width=True):
            st.session_state.queued_prompt = sample

    st.caption("Answers are generated by an AI from our FAQ and may contain mistakes. For anything important, contact support.")


# ---- show the conversation so far -------------------------------------------
def render_sources(sources) -> None:
    if sources:
        with st.expander("FAQ entries used"):
            for item in sources:
                st.markdown(f"**{item['question']}**  \n_match score: {item['score']:.2f}_")


for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])
        render_sources(message.get("sources"))

# ---- handle a new question ---------------------------------------------------
prompt = st.chat_input("Type your question here...") or st.session_state.pop("queued_prompt", None)

if prompt:
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    with st.chat_message("assistant"):
        with st.spinner("Thinking..."):
            reply = st.session_state.chatbot.ask(prompt)
        st.markdown(reply.text)
        sources = [{"question": r.faq.question, "score": r.score} for r in reply.sources]
        render_sources(sources)
        if reply.error:
            st.warning(reply.error)

    st.session_state.messages.append({"role": "assistant", "content": reply.text, "sources": sources})
